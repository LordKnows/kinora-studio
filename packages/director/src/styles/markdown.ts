import type { Style } from "./schema.js";

/** Render a style preset as a STYLE.md in the eleven-section convention. Generated; do not hand-edit. */
export function styleToMarkdown(s: Style): string {
  const L: string[] = [];
  const p = (x: string) => L.push(x);
  p(`# ${s.en} · ${s.cn} — Style Prompt`);
  p("");
  p(`> ${s.line}`);
  p(`> ${s.line_cn}`);
  if (s.references?.length) {
    p(`> References (grammar only): ${s.references.map((r) => `${r.work} (learn: ${r.learn}; don't: ${r.dontLearn})`).join("; ")}.`);
  }
  p("");
  p(`<!-- generated from style.json by @stave/director; edit the JSON. ${s.lineage ?? ""} -->`);
  p("");
  p(`**Category:** ${s.category} · ${s.category_cn}  `);
  p(`**Uses:** ${s.uses.join(" · ")}`);
  p("");
  p("## 1. Essence, and what it is not");
  p("");
  for (const e of s.essence) p(`- ${e}`);
  p("");
  for (const n of s.not) p(`- ${n}`);
  p("");
  p("## 2. Materials & rendering");
  p("");
  for (const m of s.materials) p(`- ${m}`);
  p("");
  p("## 3. Colour logic");
  p("");
  for (const r of s.colour.rules) p(`- ${r}`);
  if (s.colour.examplePalette) p(`- Example only: ${s.colour.examplePalette}`);
  p("");
  p("## 4. Type & subtitles");
  p("");
  p(`- Titles: ${s.type.titleFont}`);
  p(`- Subtitles: ${s.type.subtitleFont}`);
  p(`- Placement: ${s.type.placement}`);
  for (const r of s.type.rules ?? []) p(`- ${r}`);
  p("- Reading time: hold every caption ≥ max(1.8 s, speech + 0.6 s); CJK characters ÷ 4.5 + Latin letters ÷ 15 + 1.5 s.");
  p("");
  p("## 5. Motion quality");
  p("");
  for (const r of s.motion.rules) p(`- ${r}`);
  p(`- Stepping: on ${s.motion.stepping}${s.motion.stepping === "twos" ? " (ask for stepped motion in the beats; the camera stays smooth)" : ""}.`);
  if (s.motion.neverMoves?.length) p(`- Never moves: ${s.motion.neverMoves.join(", ")}.`);
  p(`- Shot length: action shots (characters, dialogue, more than one beat, brisk or frantic) ${s.engine.durations.action} s, at most ${s.engine.durations.maxAction} s, chained with \`continuous\` for longer action; static one-beat holds ${s.engine.durations.hold} s; periodic motion as a \`loop\` of one period. A default from cost, not a measured limit.`);
  p("");
  p("## 6. Camera grammar");
  p("");
  p("A vocabulary, not a route. Opening and ending come from the topic.");
  p("");
  p("| Move | What it expresses | Can serve |");
  p("|---|---|---|");
  for (const g of s.camera.grammar) p(`| \`${g.move}\`${g.note ? ` (${g.note})` : ""} | ${g.expresses} | ${g.serves.join("; ")} |`);
  p("");
  for (const f of s.camera.framing) p(`- Framing: ${f}`);
  p(`- Transitions: ${s.camera.transitions.join(", ")}${s.camera.forbiddenTransitions?.length ? `; never ${s.camera.forbiddenTransitions.join(", ")}` : ""}.`);
  if (s.camera.preferredLinks?.length) p(`- Preferred links: ${s.camera.preferredLinks.join(", ")}.`);
  p("");
  p("## 7. Sound palette");
  p("");
  p(`- Instruments: ${s.sound.instruments.join(", ")}.`);
  p(`- Foley: ${s.sound.foley.join("; ")}.`);
  p(`- Ambience: ${s.sound.ambience}.`);
  p(`- Silence: ${s.sound.silence}.`);
  p(`- Voice: ${s.sound.voice}.`);
  p(`- Default score field: ${s.sound.musicDefault}${s.sound.bpmRange && s.sound.bpmRange[1] > 0 ? ` (${s.sound.bpmRange[0]}–${s.sound.bpmRange[1]} BPM)` : ""}.`);
  p("- Mix: duck music under voice and key foley; loudness −14 LUFS at export.");
  p("");
  p("## 8. Native moves");
  p("");
  p("A menu: use the ones your story needs.");
  p("");
  for (const m of s.nativeMoves) p(`- **${m.name}.** ${m.what} *Build:* ${m.build} *Fits content like:* ${m.fits.join("; ")}.`);
  p("");
  p("## 9. Pitfalls of the medium (what H3 gets wrong)");
  p("");
  for (const x of s.pitfalls) p(`- ${x.problem} → ${x.fix}`);
  p("");
  p("## 10. Engine (compiled Studio fields)");
  p("");
  p("```json");
  p(JSON.stringify({ look: s.engine.look, negative: s.engine.negative, cinematography: s.engine.cinematography, bySize: s.engine.bySize ?? {}, loras: s.engine.loras, beatSuffix: s.engine.beatSuffix ?? "" }, null, 2));
  p("```");
  p("");
  if (s.engine.loraSuggestions.length) {
    p("Style LoRAs that may suit it (not applied by default; none has been rendered with this preset, so try one probe take with and without):");
    p("");
    for (const l of s.engine.loraSuggestions) p(`- \`${l.id}\` at ${l.strength}: ${l.when}`);
    p("");
  }
  p("Apply with `compile_look` (→ `start_film` / `update_look`) and `apply_style` (→ `save_shotlist`).");
  p("");
  p("## 11. Variation space");
  p("");
  p(`You decide: ${s.variation.decides.join(", ")}.`);
  p("");
  p(`- Structures: ${s.variation.structures.join("; ")}.`);
  p(`- Openings: ${s.variation.openings.join("; ")}.`);
  p(`- Endings: ${s.variation.endings.join("; ")}.`);
  p("");
  return L.join("\n");
}
