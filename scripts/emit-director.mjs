// packages/director/styles/*/style.json and its docs are the source; this
// writes src/director/generated.ts so the director layer runs inside the
// Studio MCP on Workers (no filesystem there). Runs before dev/build.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../packages/director/", import.meta.url);
const stylesDir = new URL("styles/", root).pathname;
const styles = [];
for (const name of readdirSync(stylesDir, { withFileTypes: true })) {
  if (!name.isDirectory() || name.name.startsWith("_")) continue;
  const file = join(stylesDir, name.name, "style.json");
  if (!existsSync(file)) continue;
  styles.push(JSON.parse(readFileSync(file, "utf8")));
}
styles.sort((a, b) => String(a.slug).localeCompare(String(b.slug)));
const doc = (p) => readFileSync(new URL(p, root), "utf8");
const out = `/* Generated by scripts/emit-director.mjs from packages/director — do not edit. */
export const STYLE_LIBRARY_RAW: unknown[] = ${JSON.stringify(styles)};
export const DIRECTOR_DOC: string = ${JSON.stringify(doc("docs/DIRECTOR.md"))};
export const TECHNIQUE_DOC: string = ${JSON.stringify(doc("docs/TECHNIQUE-H3.md"))};
export const STYLES_INDEX_DOC: string = ${JSON.stringify(doc("styles/README.md"))};
`;
writeFileSync(new URL("../src/director/generated.ts", import.meta.url), out);
console.log(`wrote src/director/generated.ts (${styles.length} styles)`);
