// Builds src/studio/references-data.ts, the Canvas reference catalog, from a
// checkout of github.com/anhao/ai-pose-gallery-zh (its data/ folder only):
//
//   node scripts/import-references.mjs /path/to/ai-pose-gallery-zh
//
// Only metadata is kept. No image is downloaded: every picture is referenced
// on the site that publishes it, and the Studio fetches a single picture at
// the moment it is used (the galleries allow one-at-a-time use as a generation
// reference and forbid bulk download and redistribution). URLs follow each
// site's own layout and are checked here against the source rows.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("usage: node scripts/import-references.mjs /path/to/ai-pose-gallery-zh");
  process.exit(1);
}
const read = (p) => JSON.parse(readFileSync(join(root, "data", p), "utf8"));
const fail = (msg) => {
  console.error(`import-references: ${msg}`);
  process.exit(1);
};
let revision = "unknown";
try {
  revision = execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
} catch {
  /* not a git checkout */
}

/* ---------- poses: 288 poses × 5 angles, line art + depth ---------- */

const SYSTEMS = { "全身单人・标准系": "standard", "全身单人・性感系": "sensual", "上半身单人": "upper", "双人缠绵": "couple" };
const ANGLES = { "正面": "front", "斜侧": "diag", "侧面": "side", "俯视": "high", "仰视": "low" };
const poses = read("pose-zh.json").map((p) => {
  const sys = SYSTEMS[p["体系"]];
  const angle = ANGLES[p["角度"]];
  if (!sys || !angle) fail(`pose ${p.id}: unknown system or angle (${p["体系"]} / ${p["角度"]})`);
  if (!p.id.endsWith(`_${angle}`)) fail(`pose ${p.id}: id does not end with its angle ${angle}`);
  if (p["缩略图"] !== `thumbs/${p.id}.jpg` || p["原图"] !== `img/${p.id}.png`) fail(`pose ${p.id}: unexpected file layout`);
  return { i: p.id, s: sys, n: p["姿势编号"], c: p["分类"], t: p["姿势名称"], a: angle };
});

/* ---------- costumes: four sources ---------- */

const NSFW_COSTUME = new Set(["内衣・睡衣", "性感穿搭"]);
const costumeRow = (c, src, kind, extra = {}) => ({
  i: c.id,
  src,
  k: kind,
  c: c["分类"],
  t: c["服装名称"],
  ...(c["日文名称"] ? { j: c["日文名称"] } : {}),
  g: Array.isArray(c["标签"]) ? c["标签"] : [],
  w: c["关键词"] ?? "",
  ...(c["敏感"] === true || NSFW_COSTUME.has(c["分类"]) ? { x: 1 } : {}),
  ...extra,
});

const gia = read("costume-zh.json").map((c) => {
  if (c["缩略图"] !== `thumbs/costume/${c.id}.webp`) fail(`costume ${c.id}: unexpected file layout`);
  return costumeRow(c, "gia", "real");
});
const giaAnime = read("costume-gia-anime-zh.json").map((c) => {
  const id = c.id.replace(/^gia-anime-/, "");
  const base = "https://ai-costume-anime-gallery.pages.dev";
  if (c["缩略图"] !== `${base}/thumbs/${id}.webp` || c["预览图"] !== `${base}/img/${id}.webp` || c["原图"] !== `${base}/png/${id}.png`) fail(`costume ${c.id}: unexpected URL layout`);
  return costumeRow(c, "gia-anime", "anime");
});
const charadb = read("costume-anime-zh.json").map((c) => {
  const id = c.id.replace(/^charadb-/, "");
  if (c["缩略图"] !== `https://charadb-2fi.pages.dev/thumb/${id}.webp` || c["原图"] !== `https://charadb-2fi.pages.dev/img/${id}.jpg`) fail(`costume ${c.id}: unexpected URL layout`);
  return costumeRow(c, "charadb", "anime");
});
/* Shisei is CC0 and lives on GitHub: its pictures are referenced there, at a fixed revision. */
const manifest = new Map(read("shisei/images-manifest.json").map((m) => [m.path, m.source]));
const upstream = (path) => manifest.get(path) ?? fail(`shisei: no upstream URL for ${path}`);
const shisei = read("costume-shisei-zh.json").map((c) =>
  costumeRow(c, "shisei", "real", {
    v: (c.views ?? []).map((v) => ({ i: v.id, l: v.label, th: upstream(v["缩略图"]), im: upstream(v["原图"]) })),
  }),
);
const costumes = [...gia, ...giaAnime, ...charadb, ...shisei];

/* ---------- portraits: CC0, AI-generated, fictional adults ---------- */

const portraits = read("portrait-zh.json").map((p) => {
  if (p["缩略图"] !== `thumbs/portrait/${p.id}.webp`) fail(`portrait ${p.id}: unexpected file layout`);
  return { i: p.id, s: p["分区"], l: p["发长"], y: p["发型名称"], t: p["标题"], W: p["宽"], H: p["高"], ...(p["精选"] ? { p: 1 } : {}), ...(p["热门"] ? { o: 1 } : {}) };
});

/* ---------- write ---------- */

const ids = new Set();
for (const row of [...poses, ...costumes, ...portraits]) {
  if (ids.has(row.i)) fail(`duplicate id ${row.i}`);
  ids.add(row.i);
}
const catalog = { version: 1, source: { repository: "https://github.com/anhao/ai-pose-gallery-zh", revision }, poses, costumes, portraits };
const json = JSON.stringify(catalog);
const out = new URL("../src/studio/references-data.ts", import.meta.url);
writeFileSync(
  out,
  `/* Generated by scripts/import-references.mjs from github.com/anhao/ai-pose-gallery-zh@${revision.slice(0, 12)} — do not edit.
   Metadata only (names, categories, tags); every picture stays on the site that publishes it.
   Original galleries: ギア (@giaaibusi) — poses, depth, costumes, portraits; たき AI (@taki_auto) — CharaDB;
   wquguru — Shisei (CC0). Chinese translation: anhao. See src/studio/references.ts for the terms. */
export const REFERENCE_CATALOG_JSON = ${JSON.stringify(json)};
`,
);
console.log(`wrote ${out.pathname}: ${poses.length} poses, ${costumes.length} costumes (${gia.length} gia, ${giaAnime.length} gia-anime, ${charadb.length} charadb, ${shisei.length} shisei), ${portraits.length} portraits, ${(json.length / 1024).toFixed(0)} KB`);
